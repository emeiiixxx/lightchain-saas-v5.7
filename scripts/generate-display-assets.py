"""Regenerate bundled demo display images (requires Pillow); originals stay intact."""
from pathlib import Path
from PIL import Image, ImageOps
import hashlib
import json

root = Path(__file__).resolve().parent.parent
assets = root / 'public/assets'
output = assets / 'display-previews'
output.mkdir(exist_ok=True)
manifest, generated, hashes = {}, set(), {}
for file in sorted(assets.rglob('*')):
    if output in file.parents or file.suffix.lower() not in {'.png', '.jpg', '.jpeg', '.webp'}:
        continue
    if file.stat().st_size < 65536:
        continue
    digest = hashlib.sha256(file.read_bytes()).hexdigest()[:20]
    if digest not in hashes:
        with Image.open(file) as source:
            if getattr(source, 'is_animated', False):
                continue
            source = ImageOps.exif_transpose(source)
            entry = {'width': source.width, 'height': source.height}
            for size in (320, 960):
                image = source.convert('RGBA' if 'A' in source.getbands() else 'RGB')
                image.thumbnail((size, size), Image.Resampling.LANCZOS)
                name = f'{digest}-{size}.webp'
                if not (output / name).exists():
                    image.save(output / name, 'WEBP', quality=85, method=6)
                entry[str(size)] = f'assets/display-previews/{name}'
                generated.add(name)
            hashes[digest] = entry
    manifest[file.relative_to(root / 'public').as_posix()] = hashes[digest]
# This directory is exclusively generated by this script.
for file in output.glob('*.webp'):
    if file.name not in generated:
        file.unlink()
(root / 'src/asset-display-images.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
print(f'{len(manifest)} image paths, {len(hashes)} unique images, {sum(p.stat().st_size for p in output.glob("*.webp")):,} display bytes')
